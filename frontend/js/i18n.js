  const textOriginals = new WeakMap();
  const attributeOriginals = new WeakMap();
  const languageKey = 'micropay-language';
  const root = document.documentElement;
  let language = 'fr';

  try {
    const savedLanguage = localStorage.getItem(languageKey);
    if (savedLanguage === 'fr' || savedLanguage === 'en') language = savedLanguage;
  } catch (error) {
    console.warn('La préférence de langue ne peut pas être lue.', error);
  }

  function translate(source) {
    if (language === 'fr') return source;
    const key = source.trim();
    if (translations[key]) return translations[key];
    for (const [pattern, formatter] of dynamicTranslations) {
      const match = key.match(pattern);
      if (match) return formatter(...match);
    }
    return source;
  }

  function preserveWhitespace(source, translated) {
    const leading = source.match(/^\s*/)[0];
    const trailing = source.match(/\s*$/)[0];
    return `${leading}${translated}${trailing}`;
  }

  function translateTextNode(node) {
    const current = node.nodeValue;
    let state = textOriginals.get(node);
    if (!state || current !== state.rendered) state = { source: current, rendered: current };
    const value = renderText(state.source);
    state.rendered = value;
    textOriginals.set(node, state);
    if (node.nodeValue !== value) node.nodeValue = value;
  }

  function renderText(source) {
    const translated = translate(source.trim());
    return translated === source.trim() ? source : preserveWhitespace(source, translated);
  }

  function translateAttributes(element) {
    const translatableAttributes = ['aria-label', 'aria-description', 'alt', 'placeholder', 'title', 'content'];
    let originals = attributeOriginals.get(element);
    if (!originals) {
      originals = new Map();
      attributeOriginals.set(element, originals);
    }
    translatableAttributes.forEach((name) => {
      if (!element.hasAttribute(name)) return;
      const current = element.getAttribute(name);
      let state = originals.get(name);
      if (!state || current !== state.rendered) state = { source: current, rendered: current };
      const value = translate(state.source);
      state.rendered = value;
      originals.set(name, state);
      if (element.getAttribute(name) !== value) element.setAttribute(name, value);
    });
  }

  function applyLanguage() {
    root.lang = language;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (!node.parentElement?.closest('script, style, noscript')) translateTextNode(node);
      node = walker.nextNode();
    }
    root.querySelectorAll('*').forEach(translateAttributes);
    const selector = document.querySelector('[data-language-select]');
    if (selector) selector.value = language;
  }

  function setLanguage(nextLanguage) {
    if (nextLanguage !== 'fr' && nextLanguage !== 'en') return;
    language = nextLanguage;
    applyLanguage();
    try {
      localStorage.setItem(languageKey, language);
    } catch (error) {
      console.warn('La préférence de langue ne peut pas être enregistrée.', error);
    }
    document.dispatchEvent(new CustomEvent('micropay:languagechange', {
      detail: { language },
    }));
  }

  const languageSelect = document.querySelector('[data-language-select]');
  if (languageSelect) {
    languageSelect.addEventListener('change', () => setLanguage(languageSelect.value));
  }

  window.microPayI18n = {
    get language() {
      return language;
    },
    get locale() {
      return language === 'en' ? 'en-US' : 'fr-FR';
    },
    get speechLanguage() {
      return language === 'en' ? 'en-US' : 'fr-FR';
    },
    setLanguage,
    t: translate,
  };

  applyLanguage();

  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === 'characterData') {
        translateTextNode(mutation.target);
      } else if (mutation.type === 'attributes') {
        translateAttributes(mutation.target);
      } else {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) {
            translateTextNode(node);
          } else if (node.nodeType === Node.ELEMENT_NODE) {
            translateAttributes(node);
            const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
            let textNode = walker.nextNode();
            while (textNode) {
              if (!textNode.parentElement?.closest('script, style, noscript')) translateTextNode(textNode);
              textNode = walker.nextNode();
            }
            node.querySelectorAll('*').forEach(translateAttributes);
          }
        });
      }
    });
  });
  observer.observe(root, {
    attributes: true,
    attributeFilter: ['aria-label', 'aria-description', 'alt', 'placeholder', 'title', 'content'],
    characterData: true,
    childList: true,
    subtree: true,
  });
